print("\nUnification Process:")

result = unify(expr1, expr2)

print("\nFinal Result:")

if result is None:
    print("UNIFICATION FAILURE")
elif not result:
    print("NIL - No substitution required")
else:
    print("UNIFICATION SUCCESSFUL")
    print("SUBST =", result)
    print("Expression 1:", apply_substitution(expr1, result))
    print("Expression 2:", apply_substitution(expr2, result))