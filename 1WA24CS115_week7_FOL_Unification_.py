def is_variable(x):
    return isinstance(x, str) and x.startswith('?')


def apply_substitution(x, subst):
    if is_variable(x):
        while x in subst:
            x = subst[x]
        return x

    if isinstance(x, tuple):
        return tuple(apply_substitution(i, subst) for i in x)

    return x


def occurs(var, expr, subst):
    expr = apply_substitution(expr, subst)

    if var == expr:
        return True

    if isinstance(expr, tuple):
        return any(occurs(var, i, subst) for i in expr)

    return False


def unify(x, y, subst=None):

    if subst is None:
        subst = {}

    x = apply_substitution(x, subst)
    y = apply_substitution(y, subst)

    print("Comparing:", x, "and", y)

    if x == y:
        print("Identical: NIL")
        return subst

    if is_variable(x):
        if occurs(x, y, subst):
            return None
        subst[x] = y
        print("Substitution:", x, "=", y)
        return subst

    if is_variable(y):
        if occurs(y, x, subst):
            return None
        subst[y] = x
        print("Substitution:", y, "=", x)
        return subst

    if not isinstance(x, tuple) or not isinstance(y, tuple):
        return None

    if x[0] != y[0]:
        print("Predicate mismatch!")
        return None

    if len(x) != len(y):
        print("Different number of arguments!")
        return None

    for i in range(1, len(x)):
        result = unify(x[i], y[i], subst)

        if result is None:
            return None

        subst = result

    return subst


expr1 = ('P', '?x', 'a', '?y')
expr2 = ('P', 'b', 'a', 'c')
