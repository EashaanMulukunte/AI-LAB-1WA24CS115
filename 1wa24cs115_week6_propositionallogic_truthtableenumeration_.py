from itertools import product

def implies(a, b):
    return not a or b

print("Name:Eashaan, USN: 1WA24CS115")
print(" Q | P | R | KB | R | R->P | Q->R")
print("--------------------------------")

models = []

for Q, P, R in product([True, False], repeat=3):

    # Knowledge Base
    KB = (
        implies(Q, P) and
        implies(P, not Q) and
        (Q or R)
    )

    # Queries
    q1 = R
    q2 = implies(R, P)
    q3 = implies(Q, R)

    print(
        f" {int(Q)}  {int(P)}  {int(R)} |"
        f" {int(KB)}  | {int(q1)} |"
        f"  {int(q2)}   |  {int(q3)}"
    )

    if KB:
        models.append((q1, q2, q3))

# Check entailment
entails_R = all(m[0] for m in models)
entails_R_implies_P = all(m[1] for m in models)
entails_Q_implies_R = all(m[2] for m in models)

print("--------------------------------")
print("Entailment Results:")
print("KB |= R       :", entails_R)
print("KB |= R -> P  :", entails_R_implies_P)
print("KB |= Q -> R  :", entails_Q_implies_R)

