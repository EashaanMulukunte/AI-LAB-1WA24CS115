facts = {
    ("American", "Robert"),
    ("Missile", "T1"),
    ("Owns", "A", "T1"),
    ("Enemy", "A", "America")
}

def forward_chaining(facts):

    print("Name: Eashaan M, USN: 1WA24CS115")
    print("Initial Facts:")
    for fact in facts:
        print(fact)

    print("\nApplying Rules...\n")

    while True:
        new_facts = set()

        for fact in facts:
            if fact[0] == "Missile":
                new_facts.add(("Weapon", fact[1]))

        for missile in facts:
            if missile[0] == "Missile":
                x = missile[1]

                if ("Owns", "A", x) in facts:
                    new_facts.add(("Sells", "Robert", x, "A"))

        for fact in facts:
            if fact[0] == "Enemy":
                new_facts.add(("Hostile", fact[1]))

        for person in facts:
            if person[0] == "American":
                p = person[1]

                for weapon in facts:
                    if weapon[0] == "Weapon":
                        q = weapon[1]

                        for sale in facts:
                            if sale[0] == "Sells":
                                seller = sale[1]
                                sold_item = sale[2]
                                country = sale[3]

                                if seller == p and sold_item == q:
                                    if ("Hostile", country) in facts:
                                        new_facts.add(("Criminal", p))

        new_facts = new_facts - facts

        if not new_facts:
            break

        for fact in new_facts:
            print("New Fact:", fact)

        facts.update(new_facts)

    print("\nFinal Result:")

    if ("Criminal", "Robert") in facts:
        print("Robert is a Criminal!")
    else:
        print("Robert is not proven to be a Criminal.")


forward_chaining(facts)